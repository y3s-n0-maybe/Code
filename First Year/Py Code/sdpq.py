input1 = int(input("First number: "))
input2 = int(input("Second number: "))
operation = input("Operation: ")

if operation == "+": print(input1, " + ", input2, " = ", input1+input2)
elif operation == "-": print(input1, " - ", input2, " = ", input1-input2)
elif operation == "*": print(input1, " * ", input2, " = ", input1*input2)
elif operation == "/" : print(input1, " / ", input2, " = ", input1/input2)

